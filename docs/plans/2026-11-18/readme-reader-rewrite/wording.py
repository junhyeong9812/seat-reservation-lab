PAIR = {'을': ('을', '를'), '를': ('을', '를'), '은': ('은', '는'), '는': ('은', '는'), '이': ('이', '가'), '가': ('이', '가'), '과': ('과', '와'), '와': ('과', '와'), '으로': ('으로', '로'), '로': ('으로', '로')}
def josa(m, b):
    """치환한 말의 받침에 맞춰 바로 뒤 조사를 고른다 (역참조가 있는 규칙은 조사를 그대로 둔다)"""
    j = m.group('josa') or ''
    out = m.expand(b) if '\\' in b else b
    if not j or '\\' in b: return out + j
    last = [c for c in out if '가' <= c <= '힣']
    if not last: return out + j
    code = (ord(last[-1]) - 0xAC00) % 28
    has = code != 0
    if j in ('으로', '로'): return out + ('으로' if has and code != 8 else '로')
    return out + PAIR[j][0 if has else 1]
PROT = re.compile(r'```.*?```|`[^`\n]*`|\]\([^)\n]*\)|사용자: ?"[^"\n]*"(?: ?→ ?"[^"\n]*")*|사용자 제안[^"\n]*"[^"\n]*"', re.S)
def convert(s):
    out, i, n = [], 0, 0
    def sub(t):
        nonlocal n
        for a, b in R:
            t, k = re.subn(a + r'(?P<josa>(?:으로|로|을|를|은|는|이|가|과|와)(?=[ ,.)·]))?', lambda m, b=b: josa(m, b), t); n += k
        return t
    for m in PROT.finditer(s):
        out.append(sub(s[i:m.start()])); out.append(m.group(0)); i = m.end()
    out.append(sub(s[i:])); return ''.join(out), n
